"""Generate the CPython 3.13/Unicode 15.1 repr table; --check verifies a checkout."""
import argparse
from pathlib import Path
import sys
import unicodedata


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', required=True, type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    assert sys.version_info[:2] == (3, 13) and unicodedata.unidata_version == '15.1.0'
    ranges = []
    for code in range(0x110000):
        if chr(code).isprintable():
            continue
        if ranges and ranges[-1][1] + 1 == code:
            ranges[-1][1] = code
        else:
            ranges.append([code, code])
    text = '''//! CPython 3.13 / Unicode 15.1 non-printable ranges used by str.__repr__.
//! Generated by STAR Lab tools/rust_migration/generate_unicode_repr.py.
//! Includes unassigned/private-use/separator characters; ASCII space is printable.
//! Do not substitute Rust's Unicode version or locale-dependent classification.
const NONPRINTABLE: &[(u32, u32)] = &[
'''
    text += ''.join(f'    (0x{a:x}, 0x{b:x}),\n' for a, b in ranges)
    text += '''];

pub(crate) fn printable(c: char) -> bool {
    if c.is_ascii() {
        return !c.is_ascii_control();
    }
    let code = c as u32;
    let index = NONPRINTABLE.partition_point(|(start, _)| *start <= code);
    index == 0 || code > NONPRINTABLE[index - 1].1
}
'''
    path = args.source / 'native/rotk/src/unicode_repr.rs'
    if args.check:
        assert path.read_text() == text, 'Unicode repr table differs from the Python oracle'
    else:
        path.write_text(text)
    print(f'Unicode {unicodedata.unidata_version}: {len(ranges)} ranges; check={args.check}')


if __name__ == '__main__':
    main()
